#!/usr/bin/env bash
# Install (or remove) the macOS launchd job that installs planned fonts and trashes the originals.
# Fonts can only be installed natively on macOS, so this part of the routine runs here.
#
#   bash install-fonts-job.sh               install / update (weekly, Sunday 22:00)
#   bash install-fonts-job.sh --run-now     install, then run once now (grants macOS permission prompts)
#   bash install-fonts-job.sh --uninstall   remove the job (keeps the repo and your state)
#
# Environment (optional):
#   FO_SOURCE  folder the routine organises   (default ~/Downloads)
#   FO_HOME    state / rules / reports folder (default $FO_SOURCE/.file-organizer)
#   FO_REPO    where the repo is cloned       (default ~/.file-organizer/file-organizer)
#   FO_HOUR / FO_MINUTE / FO_WEEKDAY  schedule (default 22 / 0 / 0 = Sunday)
set -euo pipefail

LABEL="io.github.ayhid.file-organizer.fonts"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
FO_SOURCE="${FO_SOURCE:-$HOME/Downloads}"
FO_HOME="${FO_HOME:-$FO_SOURCE/.file-organizer}"
FO_REPO="${FO_REPO:-$HOME/.file-organizer/file-organizer}"
RUNNER="$HOME/.file-organizer/run-fonts.sh"
HOUR="${FO_HOUR:-22}"; MINUTE="${FO_MINUTE:-0}"; WEEKDAY="${FO_WEEKDAY:-0}"

if [ "$(uname)" != "Darwin" ]; then echo "This installer is for macOS."; exit 1; fi

if [ "${1:-}" = "--uninstall" ]; then
  launchctl bootout "gui/$(id -u)" "$PLIST" 2>/dev/null || true
  rm -f "$PLIST" "$RUNNER"
  echo "Removed $LABEL (repo and state kept)."
  exit 0
fi

# 1. repo
mkdir -p "$(dirname "$FO_REPO")" "$FO_HOME/logs"
if [ -d "$FO_REPO/.git" ]; then
  git -C "$FO_REPO" pull -q --ff-only || echo "warning: could not update $FO_REPO, using the current version"
else
  git clone -q https://github.com/ayhid/file-organizer "$FO_REPO"
fi

# 2. python >= 3.9, with tomli below 3.11
PY=""
for c in /opt/homebrew/bin/python3 /usr/local/bin/python3 /usr/bin/python3 "$(command -v python3 || true)"; do
  if [ -n "$c" ] && [ -x "$c" ] && "$c" -c 'import sys; sys.exit(sys.version_info < (3, 9))' 2>/dev/null; then
    PY="$c"; break
  fi
done
[ -n "$PY" ] || { echo "Python 3.9+ not found. Install it (xcode-select --install or brew install python)."; exit 1; }
if ! "$PY" -c 'import sys; sys.exit(sys.version_info < (3, 11))' 2>/dev/null; then
  "$PY" -c 'import tomli' 2>/dev/null || "$PY" -m pip install --user --quiet tomli
fi
echo "python: $PY ($("$PY" --version 2>&1))"

[ -f "$FO_HOME/rules.local.toml" ] || echo "note: no $FO_HOME/rules.local.toml yet (generic rules only)"

# 3. runner (launchd has a minimal PATH, so everything is absolute)
cat > "$RUNNER" <<EOF
#!/bin/bash
# Generated by install-fonts-job.sh. Installs planned fonts, then trashes the originals.
LOG="$FO_HOME/logs/fonts.log"
{
  echo "=== \$(date '+%Y-%m-%d %H:%M:%S')"
  /usr/bin/git -C "$FO_REPO" pull -q --ff-only 2>&1 || echo "repo update skipped"
  if [ ! -f "$FO_HOME/state.db" ]; then echo "no plan yet ($FO_HOME/state.db missing)"; exit 0; fi
  "$PY" "$FO_REPO/fo/apply.py" --only install --apply \\
      --source "$FO_SOURCE" --target "$HOME/Documents/Organized" \\
      --state "$FO_HOME/state.db" --local-rules "$FO_HOME/rules.local.toml"
  echo "exit \$?"
} >> "\$LOG" 2>&1
EOF
chmod +x "$RUNNER"

# 4. launchd agent (runs at the next wake if the Mac was asleep at the scheduled time)
mkdir -p "$HOME/Library/LaunchAgents"
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>/bin/bash</string><string>$RUNNER</string></array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Weekday</key><integer>$WEEKDAY</integer>
    <key>Hour</key><integer>$HOUR</integer>
    <key>Minute</key><integer>$MINUTE</integer>
  </dict>
  <key>StandardOutPath</key><string>$FO_HOME/logs/launchd.out.log</string>
  <key>StandardErrorPath</key><string>$FO_HOME/logs/launchd.err.log</string>
</dict>
</plist>
EOF
plutil -lint "$PLIST" >/dev/null
launchctl bootout "gui/$(id -u)" "$PLIST" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
printf 'Installed %s: weekday %s at %02d:%02d\nLog: %s\n' "$LABEL" "$WEEKDAY" "$HOUR" "$MINUTE" "$FO_HOME/logs/fonts.log"

if [ "${1:-}" = "--run-now" ]; then
  echo "Running once now (accept any macOS permission prompt for Finder / Terminal)..."
  bash "$RUNNER"
  tail -n 20 "$FO_HOME/logs/fonts.log"
fi
